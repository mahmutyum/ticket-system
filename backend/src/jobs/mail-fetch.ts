/**
 * Gelen kutusu turu — şirket posta kutularındaki okunmamış e-postaları işler.
 *
 * Eşleştirme: konudaki ticket numarası + gönderen = talep sahibi + aynı şirket.
 * Üçü birden tutmazsa e-posta "eşleşmeyen" sayılır (başka birinin ticket'ına not
 * enjekte edilemesin; ticket'ın varlığı da ifşa edilmesin). Eşleşmeyenden,
 * posta kutusu ayarı açıksa yeni ticket açılır.
 *
 * Her ileti `inbound_messages`'a (posta kutusu + Message-ID tekil) yazılır:
 * okundu işareti başarısız olsa bile aynı ileti ikinci kez işlenmez.
 */

export type InboundAction = 'reply' | 'created' | 'ignored' | 'failed';

export interface InboundResult {
  action: InboundAction;
  reason?: string;
  ticketId?: string;
}

export interface MailFetchDeps extends IntakeDeps {
  createSource?: (mailbox: CompanyMailbox) => MailSource;
}

/** Tek turda posta kutusu başına en fazla ileti. */
const BATCH = 25;
/** Gönderen başına saatlik üst sınır (döngü / taşma koruması). */
const SENDER_HOURLY_LIMIT = 30;

const truncate = (value: string, max: number) => (value.length > max ? `${value.slice(0, max - 1)}…` : value);

/** "Re: Fwd: YNT: İLT:" gibi önekleri atar. */
function cleanSubject(subject: string): string {
  return subject.replace(/^(\s*(re|fw|fwd|ynt|yan|ilt|i̇lt|tr|aw|wg)\s*:\s*)+/i, '').trim();
}

async function saveAttachments(prisma: PrismaClient, ticketId: string, mail: ParsedMail): Promise<number> {
  if (mail.attachments.length === 0) return 0;
  const usage = await prisma.attachment.aggregate({ where: { ticketId }, _count: true, _sum: { fileSize: true } });
  let count = usage._count;
  let total = usage._sum.fileSize ?? 0;
  let skipped = 0;
  for (const file of mail.attachments) {
    // Portal yüklemesiyle aynı kurallar: MIME allowlist + imza + boyut + ticket kotası.
    const ok =
      isAllowedMimeType(file.contentType) &&
      isBufferConsistentWithMime(file.content, file.contentType) &&
      file.content.length <= config.MAX_FILE_SIZE &&
      count < ATTACHMENT_LIMITS.maxCount &&
      total + file.content.length <= ATTACHMENT_LIMITS.maxTotalBytes;
    if (!ok) {
      skipped++;
      continue;
    }
    const saved = await saveFile(file.content, file.filename, ticketId, file.contentType);
    await prisma.attachment.create({
      data: {
        ticketId,
        fileName: saved.fileName,
        filePath: saved.filePath,
        fileSize: saved.fileSize,
        mimeType: file.contentType,
        uploadedBy: mail.fromEmail,
      },
    });
    count++;
    total += saved.fileSize;
  }
  return skipped;
}

export async function processInboundMail(
  prisma: PrismaClient,
  mailbox: CompanyMailbox,
  mail: ParsedMail,
  now: Date,
  deps: IntakeDeps,
): Promise<InboundResult> {
  if (!mail.fromEmail) return { action: 'ignored', reason: 'no_sender' };
  if (mail.autoGenerated) return { action: 'ignored', reason: 'auto_generated' };
  if (mail.fromEmail === mailbox.address.toLowerCase()) return { action: 'ignored', reason: 'own_address' };

  const recent = await prisma.inboundMessage.count({
    where: { mailboxId: mailbox.id, fromEmail: mail.fromEmail, receivedAt: { gte: new Date(now.getTime() - 60 * 60 * 1000) } },
  });
  if (recent >= SENDER_HOURLY_LIMIT) return { action: 'ignored', reason: 'rate_limited' };

  const ticketNumber = extractTicketNumber(mail.subject);
  let closedTicketNumber: string | null = null;

  if (ticketNumber) {
    let ticket = await prisma.ticket.findUnique({ where: { ticketNumber }, select: { ...replyTicketSelect, mergedIntoId: true } });
    // Birleştirilmiş ticket'a gelen yanıt hedefe yönlenir (kaynağın talep sahibi orada CC'dir).
    if (ticket?.mergedIntoId) {
      ticket = await prisma.ticket.findUnique({ where: { id: ticket.mergedIntoId }, select: { ...replyTicketSelect, mergedIntoId: true } });
    }
    // Yanıt verebilenler: talep sahibi ve CC izleyicileri (personel izleyiciler değil).
    const matches =
      !!ticket &&
      ticket.companyId === mailbox.companyId &&
      (await isRequesterSide(prisma, ticket, mail.fromEmail));
    if (ticket && matches && ticket.status !== TicketStatus.closed) {
      if (!mail.body && mail.attachments.length === 0) return { action: 'ignored', reason: 'empty', ticketId: ticket.id };
      const skipped = await saveAttachments(prisma, ticket.id, mail);
      const content = truncate(mail.body || `(${mail.attachments.length - skipped} ek)`, LIMITS.noteContent.max);
      await addRequesterReply(prisma, ticket, content, deps, { via: 'email', reopenResolved: true, authorEmail: mail.fromEmail });
      return { action: 'reply', ticketId: ticket.id, reason: skipped ? `attachments_skipped:${skipped}` : undefined };
    }
    if (ticket && matches) closedTicketNumber = ticket.ticketNumber;
  }

  // Eşleşmeyen (ya da kapanmış ticket'a gelen) e-posta → yeni ticket.
  if (!mailbox.createTickets) {
    return { action: 'ignored', reason: closedTicketNumber ? 'ticket_closed' : 'no_match' };
  }
  if (!mailbox.defaultCategoryId || !mailbox.defaultLocationId) return { action: 'ignored', reason: 'not_configured' };

  const company = await prisma.company.findUnique({
    where: { id: mailbox.companyId },
    select: { allowedDomains: true, isActive: true },
  });
  if (!company?.isActive) return { action: 'ignored', reason: 'company_inactive' };
  if (!isEmailDomainAllowed(company.allowedDomains, mail.fromEmail)) return { action: 'ignored', reason: 'domain_not_allowed' };

  const locale = mailbox.defaultLocale === 'en' ? 'en' : 'tr';
  const reference = closedTicketNumber
    ? (locale === 'en' ? `(Follow-up to closed request ${closedTicketNumber})\n\n` : `(Kapanmış ${closedTicketNumber} talebinin devamı)\n\n`)
    : '';
  const subject = cleanSubject(mail.subject) || (locale === 'en' ? 'Request by email' : 'E-posta ile talep');
  const description = reference + (mail.body || (locale === 'en' ? '(no text)' : '(metin yok)'));
  const fullName = mail.fromName.trim() || mail.fromEmail.split('@')[0];

  const ticket = await createRequesterTicket(prisma, {
    companyId: mailbox.companyId,
    locationId: mailbox.defaultLocationId,
    categoryId: mailbox.defaultCategoryId,
    email: mail.fromEmail,
    fullName: truncate(fullName.length >= LIMITS.fullName.min ? fullName : mail.fromEmail, LIMITS.fullName.max),
    subject: truncate(subject, LIMITS.ticketSubject.max),
    description: truncate(description, LIMITS.ticketDescription.max),
    priority: Priority.medium,
    locale,
    source: 'email',
    // E-postadaki diğer alıcılar CC olur (posta kutusu hariç, şirketin izinli domain'leri).
    ccEmails: mail.cc.filter(a => a !== mailbox.address.toLowerCase() && isEmailDomainAllowed(company.allowedDomains, a)),
  }, deps);
  const skipped = await saveAttachments(prisma, ticket.id, mail);
  return { action: 'created', ticketId: ticket.id, reason: skipped ? `attachments_skipped:${skipped}` : undefined };
}

export interface MailFetchSummary {
  mailboxes: number;
  processed: number;
  failedMailboxes: number;
}

export async function runMailFetch(prisma: PrismaClient, now: Date, deps: MailFetchDeps): Promise<MailFetchSummary> {
  const summary: MailFetchSummary = { mailboxes: 0, processed: 0, failedMailboxes: 0 };
  const mailboxes = await prisma.companyMailbox.findMany({ where: { isActive: true } });
  const createSource = deps.createSource ?? createMailSource;

  for (const mailbox of mailboxes) {
    if (!isMailboxConfigured(mailbox)) continue;
    summary.mailboxes++;
    let source: MailSource | null = null;
    try {
      source = createSource(mailbox);
      const mails = await source.fetchUnread(BATCH);
      for (const fetched of mails) {
        let parsed: ParsedMail | null = null;
        let result: InboundResult;
        try {
          parsed = await parseMail(fetched.raw);
          const seen = await prisma.inboundMessage.findUnique({
            where: { mailboxId_messageId: { mailboxId: mailbox.id, messageId: parsed.messageId } },
            select: { id: true },
          });
          if (seen) {
            await source.markProcessed(fetched.id);
            continue;
          }
          result = await processInboundMail(prisma, mailbox, parsed, now, deps);
        } catch (err) {
          result = { action: 'failed', reason: truncate(err instanceof Error ? err.message : String(err), 500) };
        }
        await prisma.inboundMessage.create({
          data: {
            mailboxId: mailbox.id,
            // Ayrıştırılamayan ileti kaynak kimliğiyle kaydedilir ki tekrar denenmesin.
            messageId: parsed?.messageId ?? `source:${fetched.id}`,
            fromEmail: parsed?.fromEmail ?? '',
            subject: truncate(parsed?.subject ?? '', 300),
            action: result.action,
            reason: result.reason ?? null,
            ticketId: result.ticketId ?? null,
          },
        });
        await source.markProcessed(fetched.id);
        summary.processed++;
      }
      await prisma.companyMailbox.update({ where: { id: mailbox.id }, data: { lastFetchAt: now, lastError: null } });
    } catch (err) {
      summary.failedMailboxes++;
      await prisma.companyMailbox.update({
        where: { id: mailbox.id },
        data: { lastFetchAt: now, lastError: truncate(err instanceof Error ? err.message : String(err), 500) },
      });
    } finally {
      await source?.close().catch(() => undefined);
    }
  }
  return summary;
}
