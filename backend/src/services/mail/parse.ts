import { simpleParser, type AddressObject } from 'mailparser';
import { createHash } from 'node:crypto';

/**
 * Gelen e-postanın sağlayıcıdan bağımsız temsili.
 *
 * IMAP, Microsoft Graph ve Gmail API'nin üçü de ham MIME (RFC 822) verebilir;
 * böylece ayrıştırma, döngü koruması ve alıntı kırpma TEK yerde yapılır.
 */
export interface ParsedMail {
  messageId: string;
  fromEmail: string;
  fromName: string;
  subject: string;
  /** Alıntısı kırpılmış düz metin gövde. */
  body: string;
  /** Otomatik yanıt / bülten / teslim raporu → işlenmez. */
  autoGenerated: boolean;
  attachments: Array<{ filename: string; contentType: string; content: Buffer }>;
}

const TICKET_NUMBER = /\bTKT-\d{4}-\d{5,}\b/i;

/** Konudan ticket numarasını çıkarır (`Re: Talebinize Yanıt Eklendi - TKT-2026-00042`). */
export function extractTicketNumber(subject: string): string | null {
  return TICKET_NUMBER.exec(subject)?.[0].toUpperCase() ?? null;
}

/**
 * Otomatik üretilmiş mi? (RFC 3834 + yaygın sağlayıcı başlıkları)
 *
 * Otomatik yanıtlara yanıt vermek/işlemek iki sistem arasında sonsuz döngü
 * yaratır: tatil mesajı → "talebinize yanıt eklendi" bildirimi → tatil mesajı...
 */
export function isAutoGenerated(headers: Map<string, unknown>, fromEmail: string): boolean {
  const header = (name: string) => {
    const value = headers.get(name);
    if (value === undefined || value === null) return '';
    if (typeof value === 'string') return value.toLowerCase();
    // Yapısal başlıklar (content-type vb.) `{ value, params }` olarak gelir.
    if (typeof value === 'object' && 'value' in value && typeof value.value === 'string') return value.value.toLowerCase();
    return '';
  };
  const autoSubmitted = header('auto-submitted');
  if (autoSubmitted && autoSubmitted !== 'no') return true;
  // Not: `X-Auto-Response-Suppress` burada ölçüt DEĞİLDİR — Outlook/Exchange onu
  // bazı normal kullanıcı mesajlarına da ekler; Exchange otomatik yanıtları zaten
  // `Auto-Submitted: auto-replied` taşır.
  if (headers.has('x-autoreply') || headers.has('x-autorespond')) return true;
  if (['bulk', 'junk', 'list', 'auto_reply'].includes(header('precedence'))) return true;
  // mailparser `List-Id`, `List-Unsubscribe` vb. başlıkları tek `list` anahtarında toplar.
  if (headers.has('list') || headers.has('list-id') || headers.has('list-unsubscribe')) return true;
  const local = fromEmail.split('@')[0]?.toLowerCase() ?? '';
  if (['mailer-daemon', 'postmaster', 'noreply', 'no-reply', 'do-not-reply', 'donotreply'].includes(local)) return true;
  const contentType = header('content-type');
  if (contentType.includes('multipart/report')) return true; // teslim/okundu raporları
  return false;
}

/** Yanıtın altındaki alıntılanmış önceki mesajı kırpar. */
export function stripQuotedReply(text: string): string {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const markers: RegExp[] = [
    /^On .{1,200}wrote:\s*$/i, // Gmail / Apple Mail (EN)
    /^.{1,200}tarihinde .{0,200}yazdı:\s*$/i, // Gmail (TR)
    /^-{2,}\s*(Original Message|Orijinal İleti|Özgün İleti|Forwarded message|İletilen ileti)\s*-{2,}/i,
    /^_{10,}\s*$/, // Outlook ayırıcı çizgi
    /^(From|Kimden|Gönderen):\s.+/i, // Outlook başlık bloğu
    /^>{1}/, // klasik alıntı
  ];
  const cut = lines.findIndex((line, i) => i > 0 && markers.some(re => re.test(line.trim())));
  const kept = (cut === -1 ? lines : lines.slice(0, cut)).join('\n');
  return kept.replace(/\n{3,}/g, '\n\n').trim();
}

/** HTML-only e-postalar için kaba düz metin dönüşümü (etiketleri at, blokları satıra çevir). */
export function htmlToText(html: string): string {
  return html
    .replace(/<(script|style)[^>]*>[\s\S]*?<\/\1>/gi, '')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|div|li|tr|h[1-6])>/gi, '\n')
    .replace(/<blockquote[\s\S]*$/i, '') // alıntı bloğundan sonrası
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&');
}

function firstAddress(value: AddressObject | AddressObject[] | undefined): { address: string; name: string } {
  const list = Array.isArray(value) ? value : value ? [value] : [];
  for (const group of list) {
    for (const entry of group.value) {
      if (entry.address) return { address: entry.address.toLowerCase(), name: entry.name ?? '' };
    }
  }
  return { address: '', name: '' };
}

export async function parseMail(raw: Buffer): Promise<ParsedMail> {
  const mail = await simpleParser(raw, { skipImageLinks: true, skipTextToHtml: true });
  const from = firstAddress(mail.from);
  const text = mail.text?.trim() ? mail.text : typeof mail.html === 'string' ? htmlToText(mail.html) : '';
  // Message-ID yoksa (nadiren) içerik özeti ile tekilleştirilir.
  const messageId = mail.messageId ?? `sha256:${createHash('sha256').update(raw).digest('hex')}`;
  return {
    messageId,
    fromEmail: from.address,
    fromName: from.name,
    subject: (mail.subject ?? '').trim(),
    body: stripQuotedReply(text),
    autoGenerated: isAutoGenerated(mail.headers, from.address),
    attachments: mail.attachments
      // Satır içi imza görselleri (cid:) ek sayılmaz.
      .filter(a => !a.related && a.contentDisposition !== 'inline')
      .map(a => ({ filename: a.filename ?? 'attachment', contentType: a.contentType, content: a.content })),
  };
}
