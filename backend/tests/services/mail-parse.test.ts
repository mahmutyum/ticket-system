import { describe, it, expect } from 'vitest';
import { extractTicketNumber, htmlToText, parseMail, stripQuotedReply } from '../../src/services/mail/parse.js';

const mime = (headers: string, body: string) => Buffer.from(`${headers.trim()}\n\n${body}`.replace(/\n/g, '\r\n'));

describe('extractTicketNumber', () => {
  it('yanıt öneklerinin arkasındaki numarayı bulur', () => {
    expect(extractTicketNumber('Re: Talebinize Yanıt Eklendi - TKT-2026-00042')).toBe('TKT-2026-00042');
    expect(extractTicketNumber('YNT: tkt-2026-00042 yazıcı')).toBe('TKT-2026-00042');
  });
  it('numara yoksa null', () => {
    expect(extractTicketNumber('Yazıcı çalışmıyor')).toBeNull();
    expect(extractTicketNumber('TKT-26-1')).toBeNull();
  });
});

describe('stripQuotedReply', () => {
  it('Gmail (EN) alıntısını keser', () => {
    expect(stripQuotedReply('Still broken.\n\nOn Mon, 20 Jul 2026 at 10:00, IT <it@acme.com> wrote:\n> old')).toBe('Still broken.');
  });
  it('Gmail (TR) alıntısını keser', () => {
    expect(stripQuotedReply('Hâlâ çalışmıyor.\n\n20 Tem 2026 Pzt 10:00 tarihinde IT <it@acme.com> şunu yazdı:\n> eski')).toBe('Hâlâ çalışmıyor.');
  });
  it('Outlook başlık bloğunu keser', () => {
    const text = 'Teşekkürler, düzeldi.\n\n________________________________\nKimden: IT Destek <it@acme.com>\nGönderildi: 20 Temmuz';
    expect(stripQuotedReply(text)).toBe('Teşekkürler, düzeldi.');
  });
  it('alıntı yoksa metni korur', () => {
    expect(stripQuotedReply('Tek satır\nikinci satır')).toBe('Tek satır\nikinci satır');
  });
});

describe('htmlToText', () => {
  it('etiketleri atar, blokları satıra çevirir, alıntıyı keser', () => {
    expect(htmlToText('<div>Merhaba<br>dünya</div><p>&amp; iyi günler</p><blockquote>eski</blockquote>').trim())
      .toBe('Merhaba\ndünya\n& iyi günler');
  });
});

describe('parseMail', () => {
  it('normal yanıtı ayrıştırır', async () => {
    const mail = await parseMail(mime(`
From: Ayşe Yılmaz <Ayse@Acme.com>
To: destek@acme.com
Subject: Re: TKT-2026-00042
Message-ID: <abc@acme.com>
Content-Type: text/plain; charset=utf-8
`, 'Hâlâ çalışmıyor.\n\nOn Mon, IT wrote:\n> eski'));
    expect(mail).toMatchObject({
      messageId: '<abc@acme.com>',
      fromEmail: 'ayse@acme.com',
      fromName: 'Ayşe Yılmaz',
      subject: 'Re: TKT-2026-00042',
      body: 'Hâlâ çalışmıyor.',
      autoGenerated: false,
    });
  });

  it.each([
    ['Auto-Submitted: auto-replied'],
    ['X-Autoreply: yes'],
    ['Precedence: bulk'],
    ['List-Id: <news.acme.com>'],
  ])('otomatik iletiyi işaretler (%s)', async (header) => {
    const mail = await parseMail(mime(`
From: a@acme.com
Subject: Out of office
Message-ID: <x@acme.com>
${header}
`, 'Tatildeyim'));
    expect(mail.autoGenerated).toBe(true);
  });

  it('mailer-daemon gönderen otomatik sayılır', async () => {
    const mail = await parseMail(mime('From: MAILER-DAEMON@acme.com\nSubject: Undelivered\nMessage-ID: <y@acme.com>', 'x'));
    expect(mail.autoGenerated).toBe(true);
  });

  it('Auto-Submitted: no normal iletidir', async () => {
    const mail = await parseMail(mime('From: a@acme.com\nSubject: s\nMessage-ID: <z@acme.com>\nAuto-Submitted: no', 'x'));
    expect(mail.autoGenerated).toBe(false);
  });

  it('ekleri çıkarır, Message-ID yoksa içerik özeti kullanır', async () => {
    const raw = mime(`
From: a@acme.com
Subject: Ekran görüntüsü
Content-Type: multipart/mixed; boundary="B"
`, `--B
Content-Type: text/plain; charset=utf-8

Ekte
--B
Content-Type: text/plain; name="log.txt"
Content-Disposition: attachment; filename="log.txt"

hata satırı
--B--`);
    const mail = await parseMail(raw);
    expect(mail.messageId).toMatch(/^sha256:[0-9a-f]{64}$/);
    expect(mail.attachments).toHaveLength(1);
    expect(mail.attachments[0]).toMatchObject({ filename: 'log.txt', contentType: 'text/plain' });
    expect(mail.body).toBe('Ekte');
  });

  it('yalnızca HTML gövdeyi düz metne çevirir', async () => {
    const mail = await parseMail(mime('From: a@acme.com\nSubject: s\nMessage-ID: <h@acme.com>\nContent-Type: text/html; charset=utf-8', '<p>Merhaba</p><blockquote>eski</blockquote>'));
    expect(mail.body).toBe('Merhaba');
  });
});
